// Writes typed ABIs + deployed addresses into the web app (web/src/lib/generated.ts).
//   node scripts/export-web.js
const fs = require("fs");
const path = require("path");

const names = [
  "ActivityLedger",
  "FeeManager",
  "StrategyRegistry",
  "FlexibleSavingsVault",
  "TermVault",
  "StabilityPoolVault",
  "AutoAllocator",
  "MUSDFaucet",
  "AlertCenter",
  "MezoFlowZap",
  "MezoFlowLens",
];

function artifact(n) {
  const hits = [];
  const walk = (d) => {
    for (const f of fs.readdirSync(d)) {
      const p = path.join(d, f);
      if (fs.statSync(p).isDirectory()) walk(p);
      else if (f === `${n}.json`) hits.push(p);
    }
  };
  walk(path.join(__dirname, "..", "artifacts", "contracts"));
  if (!hits.length) throw new Error(`artifact ${n} not found — run npx hardhat compile`);
  return JSON.parse(fs.readFileSync(hits[0], "utf8")).abi;
}

const dep = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "..", "deployments", "mezotestnet.json"), "utf8"));
let out = "// AUTO-GENERATED by contracts/scripts/export-web.js — do not edit by hand.\n\n";
out += `export const deployment = ${JSON.stringify(
  { chainId: dep.chainId, startBlock: dep.startBlock, deployer: dep.deployer, mezo: dep.mezo, contracts: dep.contracts },
  null,
  2
)} as const;\n\n`;
for (const n of names) {
  const id = n.charAt(0).toLowerCase() + n.slice(1) + "Abi";
  out += `export const ${id} = ${JSON.stringify(artifact(n), null, 2)} as const;\n\n`;
}
const target = path.join(__dirname, "..", "..", "web", "src", "lib", "generated.ts");
fs.writeFileSync(target, out);
console.log("wrote", target, (out.length / 1024).toFixed(1) + "kb");
